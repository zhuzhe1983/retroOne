def local_url(value):
    return re.sub(r'^/p/player\d+', '', value)


def settings(response):
    assert response.status_code == 200, response.text
    return json.loads(re.search(r'Object\.assign\(window,(\{.*?\})\);window\.EJS_threads', response.text).group(1))


def bdecode(value):
    """Independent minimal decoder to inspect public wire data in tests."""
    def read(index):
        marker = value[index:index + 1]
        if marker == b'i':
            end = value.index(b'e', index)
            return int(value[index + 1:end]), end + 1
        if marker == b'd':
            result = {}
            index += 1
            while value[index:index + 1] != b'e':
                key, index = read(index)
                result[key], index = read(index)
            return result, index + 1
        colon = value.index(b':', index)
        length = int(value[index:colon])
        return value[colon + 1:colon + 1 + length], colon + 1 + length
    result, end = read(0)
    assert end == len(value)
    return result


