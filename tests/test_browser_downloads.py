def seed_sparse_fixture_cache(app, path):
    """Known generated prefix + sparse zeros: never read a multi-GiB fixture."""
    size, current = path.stat().st_size, revision(path)
    length = torrent_module.piece_length(size)
    assert length == PIECE_LENGTH
    with path.open('rb') as stream:
        first = stream.read(PIECE_LENGTH)
    zero_piece = hashlib.sha1(b'\0' * PIECE_LENGTH).digest()
    count, tail = divmod(size, PIECE_LENGTH)
    pieces = hashlib.sha1(first).digest() + zero_piece * (count - 1)
    if tail:
        pieces += hashlib.sha1(b'\0' * tail).digest()
    cache = app.state.catalog.library_data_root / 'metadata/webtorrent'
    cache.mkdir(parents=True, exist_ok=True)
    key = hashlib.sha256((str(path) + ':' + current).encode()).hexdigest()
    (cache / (key + '.json')).write_text(json.dumps({
        'revision': current, 'piece_length': length, 'pieces': base64.b64encode(pieces).decode()}))


@pytest.mark.parametrize('platform,suffix', [('switch', '.nsp'), ('switch', '.xci'), ('psp', '.chd'),
                                            ('ps2', '.iso'), ('nds', '.nds')])
def test_original_download_is_independent_of_browser_core_bios_and_play_history(environment, platform, suffix):
    build, _, vendor, _ = environment
    app, client, game, path = build(platform, suffix, size=1024**3 + 17)
    # Large files are sparse; these tests request HEAD/short ranges only.
    seed_sparse_fixture_cache(app, path)
    for core in (vendor / 'cores').iterdir():
        core.unlink()
    endpoint = '/api/games/' + game['id']
    option = client.get(endpoint + '/download-options')
    assert option.status_code == 200 and option.headers['cache-control'] == 'no-store'
    assert option.json()['available'] and not option.json()['browser_launchable']
    assert option.json()['size_bytes'] == path.stat().st_size
    assert option.json()['name'] == game['id'] + suffix
    assert option.json()['manifest_url'].endswith(endpoint + '/download-manifest?transport=p2p')
    assert client.get(endpoint + '/browser-manifest').status_code in (403, 409)
    manifest = client.get(endpoint + '/download-manifest').json()
    assert manifest['size'] == path.stat().st_size and manifest['name'] == option.json()['name']
    assert str(path.parent) not in json.dumps(manifest)
    route = local_url(manifest['download_url'])
    head = client.head(route)
    assert head.status_code == 200 and not head.content
    assert int(head.headers['content-length']) == path.stat().st_size
    assert head.headers['content-disposition'] == f'attachment; filename="{manifest["name"]}"'
    first = client.get(route, headers={'Range': 'bytes=0-14'})
    assert first.status_code == 206 and first.content == b'generated bytes'
    assert first.headers['content-range'] == f'bytes 0-14/{manifest["size"]}'
    tail = client.get(route, headers={'Range': 'bytes=-7'})
    assert tail.status_code == 206 and tail.content == b'\0' * 7
    assert client.get(route, headers={'Range': f'bytes={manifest["size"]}-'}).status_code == 416
    assert app.state.catalog.get(game['id'])['played_at'] is None
    assert app.state.catalog.get(game['id'])['play_count'] == 0
    assert app.state.runner.stops == 0


@pytest.mark.parametrize('problem', ['disabled', 'blocked', 'stale', 'multi', 'launch_multi', 'resources',
                                     'directory', 'symlink_inside', 'symlink_outside', 'parent_symlink',
                                     'traversal', 'firmware', 'cache', 'keys'])
def test_download_routes_recheck_configuration_and_never_escape_library(environment, tmp_path, problem):
    build, roms, _, _ = environment
    app, client, game, path = build(size=1024)
    endpoint = '/api/games/' + game['id']
    manifest = client.get(endpoint + '/download-manifest').json()
    original_get = app.state.catalog.get
    replacement = {}
    if problem == 'disabled':
        app.state.catalog.game_configs.update_overrides(game, {'disabled': True})
    elif problem == 'blocked':
        replacement['blocked_reason'] = 'Invalid archive'
    elif problem == 'stale':
        path.write_bytes(b'changed file')
    elif problem in {'multi', 'launch_multi'}:
        dependency = path.with_suffix('.dat')
        dependency.write_bytes(b'external resource')
        replacement['files' if problem == 'multi' else 'launch_files'] = [str(path), str(dependency)]
    elif problem == 'resources':
        replacement['resource_root'] = str(path.parent)
    elif problem == 'directory':
        path.unlink()
        path.mkdir()
    elif problem.startswith('symlink_'):
        target = (path.parent if problem == 'symlink_inside' else tmp_path) / 'target.z64'
        target.write_bytes(b'secret target')
        path.unlink()
        path.symlink_to(target)
    else:
        if problem == 'parent_symlink':
            link = path.parent / 'alias'
            link.symlink_to(path.parent, target_is_directory=True)
            target = link / path.name
        elif problem == 'traversal':
            target = path.parent / '..' / path.parent.name / path.name
        elif problem == 'keys':
            target = path.parent / 'prod.keys'
            target.write_bytes(b'not a ROM')
        else:
            target = roms / ('firmware' if problem == 'firmware' else '.retroone/cache') / 'private.z64'
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(b'not a ROM')
        replacement.update(rom_path=str(target), files=[str(target)], launch_files=[str(target)])
    if replacement:
        app.state.catalog.get = lambda identifier: dict(original_get(identifier), **replacement)
    option = client.get(endpoint + '/download-options')
    assert option.status_code == 200 and not option.json()['available'], option.text
    for route in (endpoint + '/download-manifest', endpoint + '/download-manifest?transport=p2p',
                  local_url(manifest['download_url'])):
        response = client.get(route)
        assert response.status_code in {403, 409}, (problem, response.text)
        assert b'secret target' not in response.content
    assert app.state.runner.stops == 0


def test_download_revision_filename_and_transport_are_bound_to_catalog_entry(environment):
    build, _, _, _ = environment
    app, client, game, path = build(size=1024)
    endpoint = '/api/games/' + game['id']
    manifest = client.get(endpoint + '/download-manifest').json()
    route = local_url(manifest['download_url'])
    assert client.get(route.replace(manifest['name'], 'private.z64')).status_code == 404
    assert client.get(route.split('?')[0]).status_code == 422
    assert client.get(route.replace(manifest['revision'], '0' * 64)).status_code == 409
    assert client.get(endpoint + '/download-manifest?transport=ftp').status_code == 422
    path.write_bytes(b'updated')
    assert client.get(route).status_code == 409
    app.state.catalog.scan()
    assert client.get(route).status_code == 409
    updated = client.get(endpoint + '/download-manifest').json()
    assert updated['revision'] != manifest['revision']
    assert client.get(local_url(updated['download_url'])).content == b'updated'


