def test_large_metadata_job_is_nonblocking_and_shared_by_both_download_transports(environment, monkeypatch):
    build, _, _, _ = environment
    app, client, game, _ = build('n64', '.z64', size=2 * 1024**3 + 7)
    started, release = threading.Event(), threading.Event()
    calls = []
    def held_compute(self, path, name, expected_revision, progress):
        calls.append((path, name, path.stat().st_size))
        progress(12345)
        started.set()
        assert release.wait(5)
        raise ValueError('synthetic cancellation; no file content read')
    monkeypatch.setattr(TorrentDistribution, '_compute', held_compute)
    endpoint = '/api/games/' + game['id']
    try:
        begin = time.monotonic()
        result = client.get(endpoint + '/download-manifest?transport=p2p')
        assert time.monotonic() - begin < 1
        assert result.status_code == 202 and result.headers['retry-after'] == '2'
        assert result.headers['cache-control'] == 'no-store' and started.wait(1)
        assert result.json()['total_bytes'] == 2 * 1024**3 + 7
        for _ in range(3):
            repeat = client.get(endpoint + '/download-manifest?transport=p2p')
            assert repeat.status_code == 202 and repeat.json()['bytes_hashed'] == 12345
        assert len(calls) == 1
        http = client.get(endpoint + '/download-manifest?transport=http')
        assert http.status_code == 202 and http.headers['retry-after'] == '2'
        assert http.json()['bytes_hashed'] == 12345 and len(calls) == 1
        assert client.get(endpoint + '/browser-manifest?transport=http').status_code == 200
        assert app.state.catalog.get(game['id'])['played_at'] is None
    finally:
        release.set()


def test_dynamic_pieces_hash_exact_bytes_with_bounded_short_reads(tmp_path, monkeypatch):
    source = tmp_path / 'fixture.rom'
    content = b'pattern!' * (3 * PIECE_LENGTH // 8) + b'end'
    source.write_bytes(content)
    monkeypatch.setattr(torrent_module, 'MAX_PIECES', 2)
    distribution = TorrentDistribution(tmp_path / 'shared')
    native_fdopen = os.fdopen
    requests = []
    class ShortReads:
        def __init__(self, stream): self.stream = stream
        def __enter__(self): return self
        def __exit__(self, *args): self.stream.close()
        def fileno(self): return self.stream.fileno()
        def read(self, size):
            requests.append(size)
            return self.stream.read(min(size, 333333))
    def fdopen(fd, mode, *args, **kwargs):
        stream = native_fdopen(fd, mode, *args, **kwargs)
        return ShortReads(stream) if mode == 'rb' else stream
    monkeypatch.setattr(torrent_module.os, 'fdopen', fdopen)
    info, _, _ = distribution.info(source, 'game.rom')
    assert info['piece length'] == 2 * PIECE_LENGTH
    assert info['pieces'] == b''.join(hashlib.sha1(content[offset:offset + 2 * PIECE_LENGTH]).digest()
                                      for offset in range(0, len(content), 2 * PIECE_LENGTH))
    assert max(requests) <= torrent_module.READ_BLOCK_BYTES
    assert len(info['pieces']) == 40


def test_unlimited_experiment_keeps_default_rule_and_enabled_check(environment):
    build, _, _, _ = environment
    app, client, game, path = build('psp', '.iso', size=2 * 1024**3 + 7)
    endpoint = '/api/games/' + game['id']
    assert not game['browser_eligible']
    assert client.post(endpoint + '/launch', json={'mode': 'browser'}).status_code == 409
    options = client.get(endpoint + '/launch-options').json()['options']
    experiment = next(option for option in options if option['id'] == 'browser-http')
    assert experiment['available'] and experiment['max_bytes'] == 0
    assert client.post(endpoint + '/launch', json={'mode': 'browser-http'}).status_code == 200
    # No actual ROM bytes are downloaded by launching the iframe URL.
    app.state.catalog.game_configs.update_overrides(game, {'disabled': True})
    assert client.post(endpoint + '/launch', json={'mode': 'browser-http'}).status_code == 409
    assert client.get(endpoint + '/download-manifest').status_code == 409


