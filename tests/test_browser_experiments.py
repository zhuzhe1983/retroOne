def test_manifest_head_range_revision_and_filename_validation(environment):
    build, roms, _, _ = environment
    app, client, game, path = build(size=2 * MIB + 7)
    endpoint = '/api/games/' + game['id']
    response = client.get(endpoint + '/browser-manifest')
    assert response.status_code == 200 and response.headers['cache-control'] == 'no-store'
    manifest = response.json()
    assert manifest['size'] == path.stat().st_size
    assert str(roms) not in response.text and path.name not in response.text
    route = local_url(manifest['download_url'])
    head = client.head(route)
    assert head.status_code == 200 and head.content == b''
    assert int(head.headers['content-length']) == manifest['size']
    first = client.get(route, headers={'Range': 'bytes=0-14'})
    assert first.status_code == 206 and first.content == b'generated bytes'
    assert first.headers['content-range'] == f'bytes 0-14/{manifest["size"]}'
    tail = client.get(route, headers={'Range': 'bytes=-7'})
    assert tail.status_code == 206 and tail.content == b'\x00' * 7
    assert client.get(route, headers={'Range': f'bytes={manifest["size"]}-'}).status_code == 416
    assert client.get(route.replace(manifest['name'], 'private.nes')).status_code == 404
    assert client.get(route.split('?')[0]).status_code == 422
    assert client.get(route.replace(manifest['revision'], '0' * 64)).status_code == 409
    with path.open('r+b') as source:
        source.write(b'changed')
    assert client.get(route).status_code == 409
    app.state.catalog.scan()
    assert client.get(route).status_code == 409  # still rejects the old revision after a valid rescan
    assert client.get(endpoint + '/browser-manifest').json()['revision'] != manifest['revision']


