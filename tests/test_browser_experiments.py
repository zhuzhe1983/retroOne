def test_personal_save_names_are_unchanged_and_swarm_is_shared_between_players(environment):
    build, roms, _, _ = environment
    first, a, game, _ = build('nes', '.nes', size=65536)
    second, b, same_game, _ = build('nes', '.nes', size=65536, profile='player2')
    assert game['id'] == same_game['id']
    endpoint = '/api/games/' + game['id']
    for app, client, player in ((first, a, 'player1'), (second, b, 'player2')):
        old = settings(client.get('/play/' + game['id']))
        page = client.get('/play/' + game['id'] + '?experimental=true&transport=p2p')
        current = settings(page)
        assert current['EJS_gameName'] == old['EJS_gameName']
        assert current['EJS_gameID'] == old['EJS_gameID']
        assert current['EJS_defaultControls'] == old['EJS_defaultControls']
        namespace = '' if player == 'player1' else 'RetroOne-player2-'
        assert 'const storageNamespace=' + json.dumps(namespace) + ';' in page.text
        assert client.put(endpoint + '/save-state', content=player.encode()).status_code == 200
    assert a.get(endpoint + '/save-state').content == b'player1'
    assert b.get(endpoint + '/save-state').content == b'player2'
    ma = a.get(endpoint + '/browser-manifest?transport=p2p').json()
    mb = b.get(endpoint + '/browser-manifest?transport=p2p').json()
    assert ma['info_hash'] == mb['info_hash'] and ma['torrent_base64'] == mb['torrent_base64']
    assert ma['download_url'].startswith('/p/player1/')
    assert mb['download_url'].startswith('/p/player2/')
    assert str(roms) not in json.dumps(ma)
    for manifest in (ma, mb):
        token = parse_qs(urlsplit(manifest['tracker_path']).query)['token'][0]
        expires, signature = token.split('.')
        secret = bytes.fromhex((first.state.catalog.library_data_root / 'metadata/.webtorrent-secret').read_text())
        expected = hmac.new(secret, (manifest['info_hash'] + ':' + expires).encode(), hashlib.sha256).hexdigest()
        assert hmac.compare_digest(signature, expected)
        torrent = bdecode(base64.b64decode(manifest['torrent_base64']))
        assert torrent[b'info'][b'private'] == 1
        assert b'announce' not in torrent and b'url-list' not in torrent
        assert manifest['ice_servers'] == [] and manifest['private'] is True


def test_piece_hashes_describe_original_bytes_and_cache_corruption_is_repaired(tmp_path):
    source = tmp_path / 'fixture.z64'
    content = b'abc123' * (PIECE_LENGTH // 2) + b'final short piece'
    source.write_bytes(content)
    distribution = TorrentDistribution(tmp_path / 'shared')
    before = source.read_bytes()
    manifest = distribution.manifest(source, 'a' * 24 + '.z64', download_url='/private/download')
    torrent = bdecode(base64.b64decode(manifest['torrent_base64']))
    info = torrent[b'info']
    assert info[b'pieces'] == b''.join(hashlib.sha1(content[offset:offset + PIECE_LENGTH]).digest()
                                     for offset in range(0, len(content), PIECE_LENGTH))
    assert info[b'length'] == len(content)
    assert hashlib.sha1(bencode(info)).hexdigest() == manifest['info_hash']
    assert source.read_bytes() == before
    cache = next(distribution.cache_root.glob('*.json'))
    cached = json.loads(cache.read_text())
    cached['pieces'] = 'not valid base64!'
    cache.write_text(json.dumps(cached))
    assert distribution.manifest(source, 'a' * 24 + '.z64', download_url='/private/download')['info_hash'] == manifest['info_hash']
    assert json.loads(cache.read_text())['pieces'] != cached['pieces']


def test_torrent_rejects_changed_revision_nonregular_files_and_unsafe_names(tmp_path):
    source = tmp_path / 'fixture.z64'
    source.write_bytes(b'fixture')
    distribution = TorrentDistribution(tmp_path / 'shared')
    old = revision(source)
    source.write_bytes(b'changed')
    with pytest.raises(ValueError):
        distribution.info(source, 'game.z64', expected_revision=old)
    for unsafe in ('../secret', '/private', 'C:private', 'game\x00.z64', 'game\\file'):
        with pytest.raises(ValueError):
            distribution.info(source, unsafe)
    link = tmp_path / 'symlink.z64'
    link.symlink_to(source)
    with pytest.raises(ValueError):
        distribution.info(link, 'game.z64')
    with pytest.raises(ValueError):
        distribution.info(tmp_path, 'game.z64')


def test_installation_secret_is_atomic_across_workers_and_never_world_readable(tmp_path):
    path = tmp_path / 'shared/secret'
    with ThreadPoolExecutor(max_workers=8) as executor:
        results = list(executor.map(lambda _: installation_secret(path), range(16)))
