@pytest.mark.parametrize('problem', ['disabled', 'stale', 'dependency', 'directory', 'escape'])
def test_launch_and_manifest_do_not_bypass_configuration_or_resource_safety(environment, tmp_path, problem):
    build, _, _, _ = environment
    app, client, game, path = build()
    endpoint = '/api/games/' + game['id']
    if problem == 'disabled':
        app.state.catalog.game_configs.update_overrides(game, {'disabled': True})
    elif problem == 'stale':
        with path.open('ab') as source:
            source.write(b'changed')
    elif problem == 'dependency':
        # Change the authoritative catalog payload while leaving its game ID intact.
        dependency = path.with_suffix('.dat')
        dependency.write_bytes(b'dependency')
        original_get = app.state.catalog.get
        app.state.catalog.get = lambda value: dict(original_get(value), files=[str(path), str(dependency)])
    else:
        path.unlink()
        if problem == 'directory':
            path.mkdir()
        else:
            secret = tmp_path / 'private.z64'
            secret.write_bytes(b'private')
            path.symlink_to(secret)
    for route in ('/browser-manifest', '/browser-manifest?transport=p2p'):
        response = client.get(endpoint + route)
        assert response.status_code in {403, 409}, response.text
    result = client.post(endpoint + '/launch', json={'mode': 'browser-http'})
    assert result.status_code in {403, 409}
    options = client.get(endpoint + '/launch-options').json()['options']
    assert not next(item for item in options if item['id'] == 'browser-http')['available']


