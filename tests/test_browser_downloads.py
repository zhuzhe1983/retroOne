@pytest.mark.parametrize('disabled', ['operator', 'component', 'invalid_ice'])
def test_http_download_keeps_verified_piece_metadata_when_peer_transport_is_unavailable(environment, monkeypatch, disabled):
    build, _, _, bundle = environment
    app, client, game, _ = build('switch', '.nsp', size=65536)
    if disabled == 'operator':
        monkeypatch.setenv('RETROONE_P2P_ENABLED', '0')
    elif disabled == 'component':
        bundle.unlink()
    else:
        monkeypatch.setenv('RETROONE_WEBRTC_ICE_SERVERS', '[{"urls":"https://invalid.test"}]')
    endpoint = '/api/games/' + game['id']
    manifest = ready_manifest(client, endpoint + '/download-manifest?transport=http')
    assert manifest['size'] == 65536 and manifest['name'] == game['id'] + '.nsp'
    assert manifest['info_hash'] and manifest['torrent_base64'] and manifest['piece_length'] == PIECE_LENGTH
    assert manifest['p2p_available'] is False and manifest['tracker_path'] is None and manifest['ice_servers'] == []
    assert client.get(endpoint + '/download-manifest?transport=p2p').status_code == 503
    assert not (app.state.catalog.library_data_root / 'metadata/.webtorrent-secret').exists()
    assert app.state.catalog.get(game['id'])['played_at'] is None


